"""Assemble the whole tile set into one master sheet.

The cell tiles are floor / box / goal / player. The walls are grid-**edge**
pieces, so they ride along as their own slices instead of filling a cell -- an
engine reads one slice per name and places a wall instance on a grid line.

draw_pixels_at takes sprite-global coordinates, so the sheet is just the same
pixel lists shifted by 32px per column. The master .aseprite is the file to open
in Aseprite; the exported PNG is what a game engine consumes.

    python tools/gen_sheet.py --lua            # -> sheet_gen.lua (tiles/master.aseprite)
    python tools/gen_sheet.py --calls          # the MCP call-plan form
"""
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def _load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, name + ".py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


gm = _load("gen_murdoku")
gw = _load("gen_walls")

ORDER = ["floor", "box", "goal", "player"] + list(gw.ALL_PIECES)
N = gm.N
DIR = "tiles"
LAYERS = ("flat", "ink")
SHEET = "sheet"


def columns():
    """(name, lower-layer pixels, upper-layer pixels) for every entry on the sheet."""
    for name in ORDER:
        if name in gm.TILES:
            outline, body = gm.paint(name)
            yield name, body + outline, []
        else:
            body, detail, ink = gw.piece(name)
            yield name, body, detail + ink


def _pixels():
    """Shifted (base, shade) pixel triples for the whole strip."""
    base, shade = [], []
    for i, (name, bpx, spx) in enumerate(columns()):
        dx = i * N
        base += [(p["x"] + dx, p["y"], p["color"]) for p in bpx]
        shade += [(p["x"] + dx, p["y"], p["color"]) for p in spx]
    return base, shade


def emit_lua():
    """Write the batch-Lua builder: one dofile draws the sheet and its slices.

    The MCP stdio client path needs one Aseprite launch per call and stalls on
    this machine, so the sheet is drawn by one dofile'd script instead.
    """
    base, shade = _pixels()
    w, h = N * len(ORDER), N

    def tbl(px):
        return ",\n  ".join('{%d,%d,"%s"}' % t for t in px)

    slices = ",\n  ".join('{"%s", %d}' % (name, i * N) for i, (name, _, _) in enumerate(columns()))
    lo, up = LAYERS
    src = f"""-- generated by tools/gen_sheet.py -- do not edit by hand.
-- The engine-facing strip: one slice per tile, walls and openings as edge pieces.
local function col(h)
  return Color(tonumber(string.sub(h, 2, 3), 16),
               tonumber(string.sub(h, 4, 5), 16),
               tonumber(string.sub(h, 6, 7), 16), 255)
end
local BASE = {{
  {tbl(base)}
}}
local SHADE = {{
  {tbl(shade) or "0"}
}}
local SLICES = {{
  {slices}
}}
local spr = Sprite({w}, {h})
spr.layers[1].name = '{lo}'
local img = spr.cels[1].image
for _, e in ipairs(BASE) do img:putPixel(e[1], e[2], col(e[3])) end
if #SHADE > 1 then
  local lyr = spr:newLayer()
  lyr.name = '{up}'
  local img2 = Image({w}, {h}, spr.colorMode)
  for _, e in ipairs(SHADE) do img2:putPixel(e[1], e[2], col(e[3])) end
  spr:newCel(lyr, spr.frames[1], img2, Point(0, 0))
end
-- one slice per tile so the engine can address each by name
for _, e in ipairs(SLICES) do
  local s = spr:newSlice(Rectangle(e[2], 0, {N}, {N}))
  s.name = e[1]
end
local path = 'E:/Material/material-sokoban/{DIR}/master.aseprite'
pcall(os.remove, path)
spr:saveAs(path)
local ok = io.open(path, 'rb')
if not ok then error('failed to write ' .. path) end
ok:close()
print('SHEET_OK w=' .. {w} .. ' slices=' .. #spr.slices)
spr:close()
"""
    p = os.path.join(HERE, "sheet_gen.lua")
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(src)
    return p, w


def build_calls():
    """The MCP call-plan form of the same sheet."""
    master = f"{DIR}/master.aseprite"
    lo, up = LAYERS
    base, shade = _pixels()
    calls = [["create_canvas", {"width": N * len(ORDER), "height": N, "filename": master}]]
    for layer in (lo, up):
        calls.append(["add_layer", {"filename": master, "layer_name": layer}])
    for i, (name, _, _) in enumerate(columns()):
        calls.append(["create_slice", {"filename": master, "name": name,
                                       "x": i * N, "y": 0, "width": N, "height": N}])
    for layer, px in ((lo, base), (up, shade)):
        calls.append(["draw_pixels_at", {"filename": master, "layer_name": layer,
                                         "frame_index": 1,
                                         "pixels": [dict(zip(("x", "y", "color"), p)) for p in px]}])
    for scale, tag in ((1, ""), (4, "_4x")):
        calls.append(["export_frame", {"filename": master, "frame_index": 1,
                                       "output_filename": f"{DIR}/{SHEET}{tag}.png",
                                       "scale": scale}])
    calls.append(["get_color_stats", {"filename": master, "frame_index": 1, "top": 40}])
    return calls


def write_pngs():
    """Write the engine-facing strip from the tiles on disk, at 1x and 4x.

    The batch Lua saves `master.aseprite` only -- Aseprite's batch export cannot
    scale a sheet, and re-exporting it at 1x would leave the 4x copy to drift. So
    the PNGs are composited here from the same per-tile PNGs the engine reads,
    which also means a strip column can be checked against its tile byte for byte
    instead of trusting that both were drawn from one source.
    """
    from PIL import Image
    base = Image.new("RGBA", (N * len(ORDER), N), (0, 0, 0, 0))
    bad = []
    for i, name in enumerate(ORDER):
        src = Image.open(os.path.join(ROOT, DIR, f"{name}_1x.png")).convert("RGBA")
        if src.size != (N, N):
            bad.append(f"{name} is {src[0]}x{src[1]}, not {N}x{N}")
            continue
        x = i * N
        base.alpha_composite(src, (x, 0))
        if base.crop((x, 0, x + N, N)).tobytes() != src.tobytes():
            bad.append(f"{name} column does not match its tile")
    for scale, tag in ((1, ""), (4, "_4x")):
        im = base if scale == 1 else base.resize((base.width * 4, base.height * 4),
                                                 Image.NEAREST)
        im.save(os.path.join(ROOT, DIR, f"{SHEET}{tag}.png"))
    print(f"{DIR}/{SHEET}.png {base.width}x{base.height}  columns={len(ORDER) - len(bad)}"
          + (f"  MISMATCH {bad}" if bad else "  columns verified"))
    if bad:
        raise SystemExit(f"{len(bad)} sheet column(s) do not match their tile")


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if "--lua" in sys.argv:
        p, w = emit_lua()
        print(f"{os.path.basename(p)} written: {len(ORDER)} slices, {w}x{N}")
        sys.exit(0)
    if "--png" in sys.argv:
        write_pngs()
        sys.exit(0)
    if "--calls" in sys.argv:
        out = os.path.join(HERE, "calls_sheet.json")
        with open(out, "w", encoding="utf-8") as fh:
            json.dump(build_calls(), fh)
        print(f"calls_sheet.json written: {len(ORDER)} slices ({N * len(ORDER)}x{N})")
        sys.exit(0)
    print(__doc__)
